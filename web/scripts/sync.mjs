// Copies the contract ABIs (bots/src/abi.ts) and deployment addresses (contracts/deployments/*.json) into
// src/generated, so the web app builds on its own. Runs before `dev` and `build`; the output is committed.
import { copyFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../..");
const out = resolve(here, "../src/generated");

const abi = resolve(repo, "bots/src/abi.ts");
if (existsSync(abi)) copyFileSync(abi, resolve(out, "abi.ts"));

const dir = resolve(repo, "contracts/deployments");
if (existsSync(dir)) {
  const all = {};
  for (const f of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    all[f.replace(".json", "")] = JSON.parse(readFileSync(resolve(dir, f), "utf8")).metronome;
  }
  // Big numbers as strings: JSON numbers above 2^53 would lose precision.
  const ts =
    "// Generated by scripts/sync.mjs from contracts/deployments. Do not edit.\n\n" +
    `export const deployments = ${JSON.stringify(all, (_, v) => (typeof v === "number" && !Number.isSafeInteger(v) ? String(v) : v), 2)} as const;\n`;
  writeFileSync(resolve(out, "deployments.ts"), ts);
}
console.log("synced src/generated (abi.ts, deployments.ts)");
