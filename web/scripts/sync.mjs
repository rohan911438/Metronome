// Copies the contract ABIs (bots/src/abi.ts) and deployment addresses (contracts/deployments/*.json) into
// src/generated, so the web app builds on its own. Runs before `dev` and `build`; the output is committed.
//
// The local chain's deployments/31337.json is gitignored (every local deploy rewrites it), but its addresses are
// deterministic on a fresh Anvil. So its deployBlock is pinned to 0, and when the file is missing (CI) the committed
// entry is kept.
import { copyFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../..");
const out = resolve(here, "../src/generated");
const target = resolve(out, "deployments.ts");

const abi = resolve(repo, "bots/src/abi.ts");
if (existsSync(abi)) copyFileSync(abi, resolve(out, "abi.ts"));

const previous = existsSync(target)
  ? JSON.parse(readFileSync(target, "utf8").match(/export const deployments = ([\s\S]*?) as const;/)[1])
  : {};

const dir = resolve(repo, "contracts/deployments");
const all = {};
const labs = {};
for (const f of existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".json")) : []) {
  const json = JSON.parse(readFileSync(resolve(dir, f), "utf8"));
  all[f.replace(".json", "")] = json.metronome;
  // The sandwich lab: its own test-token market on testnet ("lab"), or next to the market locally.
  if (json.lab) labs[f.replace(".json", "")] = json.lab;
}
if (all["31337"]) all["31337"].deployBlock = 0;
else if (previous["31337"]) all["31337"] = previous["31337"];

const sort = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
const sorted = sort(all);
// Big numbers as strings: JSON numbers above 2^53 would lose precision.
const ts =
  "// Generated by scripts/sync.mjs from contracts/deployments. Do not edit.\n\n" +
  `export const deployments = ${JSON.stringify(sorted, (_, v) => (typeof v === "number" && !Number.isSafeInteger(v) ? String(v) : v), 2)} as const;\n\n` +
  `export const labs = ${JSON.stringify(sort(labs), null, 2)} as const;\n`;
writeFileSync(target, ts);
console.log("synced src/generated (abi.ts, deployments.ts)");
