// Generates src/abi.ts from the Foundry build output. Run after `forge build` whenever a contract's ABI changes.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../contracts/out");
const contracts = {
  metronomeAbi: "Metronome.sol/Metronome.json",
  miniAmmAbi: "MiniAMM.sol/MiniAMM.json",
  sandwichLabAbi: "SandwichLab.sol/SandwichLab.json",
  mockErc20Abi: "MockERC20.sol/MockERC20.json",
};

let ts = "// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit.\n\n";
for (const [name, file] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(resolve(out, file), "utf8"));
  ts += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(resolve(here, "../src/abi.ts"), ts);
console.log(`wrote src/abi.ts (${Object.keys(contracts).join(", ")})`);
